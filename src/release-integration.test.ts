describe('Release integration — Security: path traversal', () => {
  it('rejects --docs-dir with .. path separator', () => {
    const result = runCli([FIXTURE_TS, '--docs-dir', '../escape']);
    assert.equal(result.status, 1, 'Expected exit 1 for path traversal docs-dir');
  });

  it('rejects absolute --docs-dir', () => {
    const result = runCli([FIXTURE_TS, '--docs-dir', '/tmp/evil']);
    assert.equal(result.status, 1, 'Expected exit 1 for absolute docs-dir');
  });

  it('does not write outside the target repository on a normal run', () => {
    removeDocsDir(FIXTURE_TS);
    runCli([FIXTURE_TS]);

    // Verify no unexpected directories were created in the project root
    const leaked = path.join(PROJECT_ROOT, 'fixture-typescript-leak');
    assert.ok(!fs.existsSync(leaked), 'CLI leaked files outside target repository');
  });
});

describe('Release integration — CLI contract', () => {
  it('--help exits with 0 when used alone', () => {
    const result = runCli(['--help']);
    assert.equal(result.status, 0, '--help should exit 0');
    assert.ok(result.stdout.includes('ai-project-docs'), '--help output missing tool name');
  });

  it('no arguments exits with 1', () => {
    assert.equal(runCli([]).status, 1);
  });

  it('nonexistent path exits with 1 and reports "does not exist"', () => {
    const result = runCli(['/nonexistent/path/fixture-xyz-' + Date.now()]);
    assert.equal(result.status, 1);
    assert.ok(
      /does not exist/i.test(result.stdout + result.stderr),
      'Expected "does not exist" message',
    );
  });

  it('file target instead of directory exits with 1', () => {
    const tmpFile = path.join(require('node:os').tmpdir(), `release-test-file-${Date.now()}.txt`);
    fs.writeFileSync(tmpFile, 'not a directory');
    try {
      const result = runCli([tmpFile]);
      assert.equal(result.status, 1);
      assert.ok(
        /not a directory/i.test(result.stdout + result.stderr),
        'Expected "not a directory" message',
      );
    } finally {
      fs.rmSync(tmpFile, { force: true });
    }
  });

  it('unknown flag exits with 1', () => {
    assert.equal(runCli([FIXTURE_TS, '--unknown-flag-xyz']).status, 1);
  });

  it('unsupported --ai-provider exits with 1', () => {
    const result = runCli([FIXTURE_TS, '--ai-provider', 'nonexistent-provider']);
    assert.equal(result.status, 1, 'Expected exit 1 for unsupported provider');
  });

  it('--target without --export-agents exits with 1', () => {
    const result = runCli([FIXTURE_TS, '--target', 'cursor']);
    assert.equal(result.status, 1, 'Expected exit 1 for --target without --export-agents');
  });

  it('blocked docs directory exits with 3', () => {
    const blockFile = path.join(FIXTURE_TS, '.ai-docs-blocked-test');
    fs.writeFileSync(blockFile, 'blocks directory');
    try {
      const result = runCli([FIXTURE_TS, '--docs-dir', '.ai-docs-blocked-test']);
      assert.equal(result.status, 3, 'Expected exit 3 for blocked docs directory');
    } finally {
      fs.rmSync(blockFile, { force: true });
    }
  });
});
